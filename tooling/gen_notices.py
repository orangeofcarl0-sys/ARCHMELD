#!/usr/bin/env python3
"""Regenerate third_party/THIRD_PARTY_NOTICES.generated.md from Cargo.lock.

Usage: python tooling/gen_notices.py
Requires the pinned Rust toolchain (cargo +1.94.1-x86_64-pc-windows-gnu).
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    metadata = subprocess.run(
        [
            "cargo",
            "+1.94.1-x86_64-pc-windows-gnu",
            "metadata",
            "--format-version",
            "1",
            "--locked",
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    data = json.loads(metadata)
    packages = sorted(data["packages"], key=lambda pkg: (pkg["name"], pkg["version"]))
    lines = [
        "# Third-party crates (generated)",
        "",
        "Generated by `tooling/gen_notices.py` from `cargo metadata --locked`. Do not edit by hand.",
        "",
        "| crate | version | license | repository |",
        "|---|---|---|---|",
    ]
    missing: list[str] = []
    for package in packages:
        license_id = package.get("license") or (
            "SEE LICENSE FILE" if package.get("license_file") else ""
        )
        if not license_id:
            missing.append(f'{package["name"]} {package["version"]}')
        repository = (package.get("repository") or "").replace("|", "\\|")
        lines.append(
            "| "
            + package["name"]
            + " | "
            + package["version"]
            + " | "
            + license_id.replace("|", "\\|")
            + " | "
            + repository
            + " |"
        )
    lines += ["", f"Total packages: {len(packages)}"]
    if missing:
        lines += ["", "## Packages without a declared SPDX license (require manual review)", ""]
        lines += [f"- {name}" for name in missing]
    target = ROOT / "third_party/THIRD_PARTY_NOTICES.generated.md"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {target} ({len(packages)} packages, {len(missing)} without license)")
    return 0 if not missing else 1


if __name__ == "__main__":
    raise SystemExit(main())
